def reset_dir(path: Path) -> None:
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.strip() + "\n", encoding="utf-8")


def style_doc(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Inches(0.85)
    section.bottom_margin = Inches(0.85)
    section.left_margin = Inches(0.9)
    section.right_margin = Inches(0.9)

    normal = doc.styles["Normal"]
    normal.font.name = "Microsoft YaHei"
    normal.font.size = Pt(10.5)
    normal.paragraph_format.line_spacing = 1.18
    normal.paragraph_format.space_after = Pt(6)

    for style_name, size, color in [
        ("Heading 1", 16, RGBColor(11, 37, 69)),
        ("Heading 2", 13, RGBColor(31, 77, 120)),
        ("Heading 3", 11.5, RGBColor(46, 116, 181)),
    ]:
        style = doc.styles[style_name]
        style.font.name = "Microsoft YaHei"
        style.font.size = Pt(size)
        style.font.color.rgb = color
        style.paragraph_format.space_before = Pt(10)
        style.paragraph_format.space_after = Pt(5)


def write_docx(path: Path, title: str, subtitle: str, sections: list[tuple[str, list[str]]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = Document()
    style_doc(doc)

    title_p = doc.add_paragraph()
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title_run = title_p.add_run(title)
    title_run.bold = True
    title_run.font.name = "Microsoft YaHei"
    title_run.font.size = Pt(18)
    title_run.font.color.rgb = RGBColor(11, 37, 69)

    subtitle_p = doc.add_paragraph()
    subtitle_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle_run = subtitle_p.add_run(subtitle)
    subtitle_run.font.name = "Microsoft YaHei"
    subtitle_run.font.size = Pt(10)
    subtitle_run.font.color.rgb = RGBColor(85, 85, 85)

    for heading, paragraphs in sections:
        doc.add_heading(heading, level=1)
        for paragraph in paragraphs:
            if paragraph.startswith("|"):
                rows = [row.strip() for row in paragraph.splitlines() if row.strip()]
                table_rows = [[cell.strip() for cell in row.strip("|").split("|")] for row in rows if "---" not in row]
                table = doc.add_table(rows=0, cols=len(table_rows[0]))
                table.style = "Table Grid"
                for row in table_rows:
                    cells = table.add_row().cells
                    for idx, cell in enumerate(row):
                        cells[idx].text = cell
                continue
            if paragraph.startswith("- "):
                doc.add_paragraph(paragraph[2:], style="List Bullet")
            elif paragraph[:2].isdigit() and paragraph[2:4] == ". ":
                doc.add_paragraph(paragraph[4:], style="List Number")
            else:
                doc.add_paragraph(paragraph)
    doc.save(path)


def pdf_font(size: int) -> ImageFont.FreeTypeFont:
    source = FONT_PATH if FONT_PATH.exists() else FALLBACK_FONT
    return ImageFont.truetype(str(source), size)


def wrap(draw: ImageDraw.ImageDraw, text: str, font_obj: ImageFont.FreeTypeFont, max_width: int) -> list[str]:
    lines: list[str] = []
    current = ""
    for char in text:
        candidate = current + char
        if draw.textlength(candidate, font=font_obj) <= max_width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = char
    if current:
        lines.append(current)
    return lines or [""]


def write_pdf(path: Path, title: str, subtitle: str, sections: list[tuple[str, list[str]]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    width, height = 1240, 1754
    margin_x, margin_y = 105, 95
    max_width = width - margin_x * 2
    title_font = pdf_font(40)
    subtitle_font = pdf_font(21)
    heading_font = pdf_font(27)
    body_font = pdf_font(23)
    small_font = pdf_font(17)
    pages: list[Image.Image] = []

    def new_page() -> tuple[Image.Image, ImageDraw.ImageDraw, int]:
        img = Image.new("RGB", (width, height), "white")
        return img, ImageDraw.Draw(img), margin_y

    img, draw, y = new_page()

    def finish_page() -> None:
        draw.text((margin_x, height - 58), f"第 {len(pages) + 1} 页 / 模拟企业文档", fill="#64748b", font=small_font)
        pages.append(img)

    def need(space: int) -> None:
        nonlocal img, draw, y
        if y + space <= height - margin_y:
            return
        finish_page()
        img, draw, y = new_page()

    draw.text(((width - draw.textlength(title, font=title_font)) / 2, y), title, fill="#0b2545", font=title_font)
    y += 58
    draw.text(((width - draw.textlength(subtitle, font=subtitle_font)) / 2, y), subtitle, fill="#475569", font=subtitle_font)
    y += 48
    draw.line((margin_x, y, width - margin_x, y), fill="#cbd5e1", width=2)
    y += 34

    for heading, paragraphs in sections:
        need(90)
        draw.text((margin_x, y), heading, fill="#1f4d78", font=heading_font)
        y += 42
        for paragraph in paragraphs:
            text = paragraph.replace("|", "  ").replace("---", "")
            lines = wrap(draw, text, body_font, max_width)
            need(len(lines) * 32 + 20)
            for line in lines:
                draw.text((margin_x, y), line, fill="#1f2937", font=body_font)
                y += 32
            y += 12
        y += 8

    finish_page()
    pages[0].save(path, "PDF", resolution=150, save_all=True, append_images=pages[1:])


